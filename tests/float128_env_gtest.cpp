/// @brief A binary128 encoding, high QWORD first, the way the bits read.
struct Bits128 {
    uint64_t high;  ///< Sign, exponent and fraction bits 111:64.
    uint64_t low;   ///< Fraction bits 63:0.
};

/// @brief What one case gives in one rounding direction.
struct DirectedResult {
    uint64_t high;  ///< High QWORD of the result; zero when the result is not a float128.
    uint64_t low;   ///< Low QWORD, or the bit pattern of a double, float or integer result.
    int flags;      ///< The exception flags the operation raises, exactly.
};

