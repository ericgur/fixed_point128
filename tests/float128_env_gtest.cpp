/// @brief Runs one case of the table in the current rounding direction.
/// @return A float128 result's encoding, or a narrower result's bit pattern in the low QWORD.
[[nodiscard]] Bits128 RunDirectedCase(const DirectedCase& c)
{
    const float128 x(c.x.low, c.x.high);
    const float128 y(c.y.low, c.y.high);
    const float128 z(c.z.low, c.z.high);
    float128 r;
    switch (c.op) {
    case Op::add:
        r = x + y;
        break;
    case Op::sub:
        r = x - y;
        break;
    case Op::mul:
        r = x * y;
        break;
    case Op::div:
        r = x / y;
        break;
    case Op::sqrt:
        r = sqrt(x);
        break;
    case Op::fma:
        r = fma(x, y, z);
        break;
    case Op::sqr:
        r = sqr(x);
        break;
    case Op::reciprocal:
        r = reciprocal(x);
        break;
    case Op::rint:
        r = rint(x);
        break;
    case Op::nearbyint:
        r = nearbyint(x);
        break;
    case Op::floor:
        r = floor(x);
        break;
    case Op::ceil:
        r = ceil(x);
        break;
    case Op::trunc:
        r = trunc(x);
        break;
    case Op::round:
        r = round(x);
        break;
    case Op::ldexp:
        r = ldexp(x, static_cast<int>(static_cast<int64_t>(c.y.low)));
        break;
    case Op::fmod:
        r = fmod(x, y);
        break;
    case Op::remainder:
        r = remainder(x, y);
        break;
    case Op::lrint:
        return {0, static_cast<uint64_t>(static_cast<int64_t>(lrint(x)))};
    case Op::to_double:
        return {0, std::bit_cast<uint64_t>(static_cast<double>(x))};
    case Op::to_float:
        return {0, std::bit_cast<uint32_t>(static_cast<float>(x))};
    case Op::to_int32:
        return {0, static_cast<uint64_t>(static_cast<int64_t>(static_cast<int32_t>(x)))};
    case Op::to_uint64:
        return {0, static_cast<uint64_t>(x)};
    }
    uint64_t low = 0, high = 0;
    r.get_bits(low, high);
    return {high, low};
}

