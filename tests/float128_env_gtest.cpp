TEST(float128_env, FlagsStayRaisedUntilLowered)
{
    fp128::feclearexcept(FE_ALL_EXCEPT);
    [[maybe_unused]] const float128 a = float128(1) / float128(3);
    [[maybe_unused]] const float128 b = float128(1) / float128(4);
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), FE_INEXACT);

    std::fexcept_t saved {};
    fp128::fegetexceptflag(&saved, FE_ALL_EXCEPT);
    fp128::feclearexcept(FE_INEXACT);
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), 0);
    fp128::feraiseexcept(FE_OVERFLOW);
    fp128::fesetexceptflag(&saved, FE_INEXACT);
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), FE_INEXACT | FE_OVERFLOW);
    fp128::fesetexceptflag(&saved, FE_OVERFLOW);
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), FE_INEXACT);
    fp128::feclearexcept(FE_ALL_EXCEPT);

    // The float128 environment is separate from the hardware one.
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), 0);
}

TEST(float128_env, TheEnvironmentIsPerThread)
{
    fp128::feclearexcept(FE_ALL_EXCEPT);
    fp128::fesetround(FE_UPWARD);
    int other_round = 0;
    int other_flags = 0;
    float128 otherThird;
    std::thread other([&] {
        other_round = fp128::fegetround();
        [[maybe_unused]] const float128 x = float128(1) / float128(3);
        other_flags = fp128::fetestexcept(FE_ALL_EXCEPT);
        // A direction chosen here rounds here, and only here.
        fp128::fesetround(FE_DOWNWARD);
        otherThird = float128(-1) / float128(3);
    });
    other.join();
    EXPECT_EQ(other_round, FE_TONEAREST);
    EXPECT_EQ(other_flags, FE_INEXACT);
    EXPECT_EQ(fp128::fetestexcept(FE_ALL_EXCEPT), 0);
    EXPECT_EQ(fp128::fegetround(), FE_UPWARD);
    // -1/3 is -0x3FFD5555...5555 and a third of an ulp more: downward that is the next value out,
    // upward the one in.
    EXPECT_SAME(otherThird, Encoded(0xBFFD555555555555, 0x5555555555555556));
    EXPECT_SAME(float128(-1) / float128(3), Encoded(0xBFFD555555555555, 0x5555555555555555));
    fp128::fesetround(FE_TONEAREST);
}

TEST(float128_env, ConversionsFollowTheDirection)
{
    const float128 third = float128(1) / float128(3);
    {
        RoundingScope scope(FE_UPWARD);
        // to nearest, 1/3 rounds down as a double and up as a float
        EXPECT_EQ(std::bit_cast<uint64_t>(static_cast<double>(third)), 0x3FD5555555555556ull);
        EXPECT_EQ(std::bit_cast<uint32_t>(static_cast<float>(third)), 0x3EAAAAABu);
        EXPECT_EQ(std::format("{:.3e}", third), "3.334e-01");
        EXPECT_EQ(std::format("{:.3e}", -third), "-3.333e-01");
        EXPECT_EQ(std::format("{:.1a}", float128("0x1.01p0")), "0x1.1p+00");
        // to nearest, 0.1 already rounds up
        EXPECT_SAME(float128("0.1"), float128::tenth());
    }
    {
        RoundingScope scope(FE_DOWNWARD);
        EXPECT_EQ(std::bit_cast<uint64_t>(static_cast<double>(third)), 0x3FD5555555555555ull);
        EXPECT_EQ(std::bit_cast<uint32_t>(static_cast<float>(third)), 0x3EAAAAAAu);
        EXPECT_EQ(std::format("{:.3e}", third), "3.333e-01");
        EXPECT_EQ(std::format("{:.3e}", -third), "-3.334e-01");
        EXPECT_EQ(std::format("{:.2f}", float128(0.001)), "0.00");
        EXPECT_EQ(std::format("{:.2f}", float128(-0.001)), "-0.01");
        EXPECT_SAME(float128("0.1"), float128::nextDown(float128::tenth()));
    }
    {
        RoundingScope scope(FE_TOWARDZERO);
        EXPECT_EQ(std::format("{:.3e}", -third), "-3.333e-01");
        EXPECT_EQ(static_cast<int32_t>(float128(2.9)), 2);  // a C++ conversion truncates in any direction
        EXPECT_SAME(rint(float128(2.9)), float128(2));
        EXPECT_SAME(round(float128(2.5)), float128(3));  // round() ignores the direction
    }
}

TEST(float128_env, ConstantEvaluationRoundsToNearest)
{
    // A constant cannot depend on the thread that compiled it, so constant evaluation always
    // rounds to nearest; the same expression at run time follows the direction.
    constexpr float128 sum = float128::one() + ldexp(float128::one(), -200);
    static_assert(sum == float128::one());
    RoundingScope scope(FE_UPWARD);
    EXPECT_SAME(sum, float128::one());
    EXPECT_SAME(float128::one() + Pow2(-200), float128::nextUp(float128::one()));
}

TEST(float128_env, DirectedRoundingTable)
{
    // Every correctly rounded operation, bit for bit and with exactly its exception flags, in all
    // four directions. NearestIsUnchanged covers the larger tables, to nearest only; the cases here
    // are the ones a direction changes, from gen_env_cases.py's exact rationals.
    for (size_t i = 0; i < std::size(directedCases); ++i) {
        const DirectedCase& c = directedCases[i];
        for (size_t m = 0; m < std::size(modes); ++m) {
            Bits128 got {};
            int flags = 0;
            {
                RoundingScope scope(modes[m]);
                flags = FlagsOf([&] {
                    got = RunDirectedCase(c);
                    return 0;
                });
            }
            const DirectedResult& want = c.results[m];
            EXPECT_TRUE(got.high == want.high && got.low == want.low)
                << "case " << i << ", mode " << modes[m] << ": expected " << std::format("{:016X}{:016X}", want.high, want.low) << ", got "
                << std::format("{:016X}{:016X}", got.high, got.low);
            EXPECT_EQ(flags, want.flags) << "case " << i << ", mode " << modes[m];
        }
    }
}

TEST(float128_env, Exp10InEveryDirection)
{
    // exp10() rounds once, at the end, in the current direction: correctly rounded everywhere it
    // was measured but one place, with the flags of a single rounding, including the overflow and
    // underflow past either end of the range.
    for (const Exp10Case& c : exp10Cases) {
        for (size_t m = 0; m < std::size(modes); ++m) {
            float128 got;
            int flags = 0;
            {
                RoundingScope scope(modes[m]);
                flags = FlagsOf([&] {
                    got = float128::exp10(c.e);
                    return 0;
                });
            }
            const float128 want(c.results[m].low, c.results[m].high);
            if (c.bound == 0) {
                EXPECT_SAME(got, want) << " for e=" << c.e << ", mode " << modes[m];
            } else {
                EXPECT_LE(Saturate64(UlpDistance(got, want)), c.bound) << "e=" << c.e << ", mode " << modes[m];
            }
            EXPECT_EQ(flags, c.results[m].flags) << "e=" << c.e << ", mode " << modes[m];
        }
    }
}

TEST(float128_env, QuietComparisonsSignalOnlyOnSignalingNaN)
{
    // IEEE 754-2008 5.11: equality and the <cmath> predicates are the quiet comparisons, which
    // raise invalid for a signaling NaN only; the relational operators are the signaling ones,
    // which raise it for any NaN. The predicates used to raise nothing even for a signaling NaN.
    const float128 one = float128::one();
    for (const float128& operand : {float128::nan(), float128::signaling_nan()}) {
        const int want = operand.is_signaling() ? FE_INVALID : 0;
        EXPECT_EQ(FlagsOf([&] { return isless(operand, one); }), want);
        EXPECT_EQ(FlagsOf([&] { return islessequal(one, operand); }), want);
        EXPECT_EQ(FlagsOf([&] { return isgreater(operand, one); }), want);
        EXPECT_EQ(FlagsOf([&] { return isgreaterequal(one, operand); }), want);
        EXPECT_EQ(FlagsOf([&] { return islessgreater(operand, one); }), want);
        EXPECT_EQ(FlagsOf([&] { return isunordered(one, operand); }), want);
        EXPECT_EQ(FlagsOf([&] { return operand == one; }), want);
        EXPECT_EQ(FlagsOf([&] { return one != operand; }), want);
        EXPECT_EQ(FlagsOf([&] { return operand < one; }), FE_INVALID);
        EXPECT_EQ(FlagsOf([&] { return one >= operand; }), FE_INVALID);
        EXPECT_FALSE(isless(operand, one) || isgreaterequal(operand, one) || islessgreater(operand, one));
        EXPECT_TRUE(isunordered(operand, one));
    }
    // Ordered operands raise nothing, and totalorder never signals.
    EXPECT_EQ(FlagsOf([&] { return isless(one, float128(2)); }), 0);
    EXPECT_TRUE(isless(one, float128(2)));
    EXPECT_EQ(FlagsOf([&] { return totalorder(float128::signaling_nan(), one); }), 0);
}

TEST(float128_env, FlagsOfExactAndIntegerOperations)
{
    const float128 max = std::numeric_limits<float128>::max();

    // The remainders are exact, however large the operands: 1.5 * 2^16383 against the largest
    // value used to double the partial remainder in floating point, which overflowed.
    const float128 x = Encoded(0x7FFE800000000000, 0);  // 1.5 * 2^16383
    EXPECT_EQ(FlagsOf([&] { return remainder(x, max); }), 0);
    int quotient = 0;
    EXPECT_EQ(FlagsOf([&] { return remquo(-x, max, &quotient); }), 0);
    EXPECT_EQ(quotient, -1);
    EXPECT_EQ(FlagsOf([&] { return fmod(max, float128(3)); }), 0);
    EXPECT_EQ(FlagsOf([&] { return ldexp(std::numeric_limits<float128>::min(), -1); }), 0);  // an exact subnormal
    EXPECT_EQ(FlagsOf([&] { return fma(float128(1.5), float128(2), float128(-3)); }), 0);

    // logB into an integer has no answer for a zero, an infinity or a NaN: the invalid operation
    // (IEEE 754-2008 5.3.3). Into a floating point result a zero is a division by zero instead.
    EXPECT_EQ(FlagsOf([&] { return ilogb(float128()); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return ilogb(-float128::inf()); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return ilogb(float128::nan()); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return ilogb(max); }), 0);
    EXPECT_EQ(FlagsOf([&] { return logb(-float128()); }), FE_DIVBYZERO);

    // A signaling NaN is the invalid operation whatever converts or splits it. The conversion from
    // float used to let the hardware quiet it on the way to double, raising nothing.
    EXPECT_EQ(FlagsOf([&] { return float128(std::bit_cast<float>(0x7F800001u)); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return float128(std::bit_cast<float>(0x7FC00001u)); }), 0);
    EXPECT_EQ(FlagsOf([&] { return static_cast<float>(float128::signaling_nan()); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] {
                  int e = 0;
                  return frexp(float128::signaling_nan(), &e);
              }),
              FE_INVALID);

    EXPECT_EQ(FlagsOf([&] { return reciprocal(-float128()); }), FE_DIVBYZERO);
    EXPECT_EQ(FlagsOf([&] { return double_factorial(-2); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return double_factorial(-1); }), 0);
    EXPECT_EQ(FlagsOf([&] { return double_factorial(99); }), 0);

    // nextafter() is quiet, as the nextUp and nextDown it is built on: no overflow stepping to an
    // infinity, no underflow stepping onto zero.
    EXPECT_EQ(FlagsOf([&] { return nextafter(max, float128::inf()); }), 0);
    EXPECT_EQ(FlagsOf([&] { return nextafter(std::numeric_limits<float128>::denorm_min(), float128()); }), 0);

    // An integer result out of range is invalid; round() itself never raises inexact.
    EXPECT_EQ(FlagsOf([&] { return lrint(Pow2(31)); }), FE_INVALID);
    EXPECT_EQ(FlagsOf([&] { return llround(float128(2.5)); }), 0);
}

TEST(float128_env, SquareMatchesMultiplyInEveryDirection)
{
    // sqr() rounds through code of its own (float128::square()); multiplication is held bit exact
    // in every direction by DirectedRoundingTable and tools/ieee_check.py, so it is the reference.
    // Full 113 bit significands, with exponents whose squares are ordinary, subnormal or overflow.
    srand(RANDOM_SEED);
    const int32_t ranges[][2] = {{-100, 100}, {-8260, -8190}, {8180, 8200}};
    for (auto i = 0u; i < RANDOM_TEST_COUNT / 16; ++i) {
        const auto& range = ranges[i % std::size(ranges)];
        const int32_t e = range[0] + static_cast<int32_t>(get_uint32_random() % static_cast<uint32_t>(range[1] - range[0]));
        const uint64_t low = get_uint64_random();
        const uint64_t high = get_uint64_random() & 0x0000FFFFFFFFFFFFull;
        const float128 x(low, high, static_cast<uint32_t>(0x3FFF + e), get_uint32_random() & 1);
        for (const int mode : modes) {
            RoundingScope scope(mode);
            float128 viaSqr, viaMultiply;
            const int sqrFlags = FlagsOf([&] {
                viaSqr = sqr(x);
                return 0;
            });
            const int multiplyFlags = FlagsOf([&] {
                viaMultiply = x * x;
                return 0;
            });
            EXPECT_SAME(viaSqr, viaMultiply) << " for x=" << Bits(x) << ", mode " << mode;
            EXPECT_EQ(sqrFlags, multiplyFlags) << "x=" << Bits(x) << ", mode " << mode;
        }
    }
}
